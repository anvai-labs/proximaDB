"""Spec-driven request adapter over the generated REST transport (TD-126 Phase 4).

This is the thin binding layer between the hand-written ergonomic facade
(``rest_sync.py`` / ``rest_async.py``) and the generated low-level REST client in
``proximadb_sdk._generated.rest`` (openapi-python-client output, regenerated by
``make gen-python-sdk`` and drift-gated in CI).

The facade keeps full ownership of ergonomics — client construction, auth,
retries, error mapping, locality-gzip default, response coercion — and continues
to perform every HTTP call through its own ``_make_request`` seam (which the
OpenAPI contract test patches). What it delegates *here* is the part that the
OpenAPI spec actually governs: **the operation's HTTP method, URL template, and
request-body / query-param shape.** Each helper below calls the generated
operation's ``_get_kwargs`` (and, for bodied operations, the generated attrs
request model) so those wire details are derived from the published spec rather
than re-hand-coded in the facade.

Each helper returns a normalized ``RestCall``:
  * ``method``  — upper-cased HTTP verb (the generated client emits lower-case).
  * ``endpoint`` — the resolved URL path (the generated ``url``).
  * ``json``    — request body dict (or ``None``).
  * ``params``  — query params dict (or ``None``).

so the facade can keep calling
``self._make_request(call.method, call.endpoint, json=call.json, params=call.params)``.
"""

