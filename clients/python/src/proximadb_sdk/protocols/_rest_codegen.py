def _path_only(get_kwargs: Any, body: dict[str, Any], model_cls: Any) -> RestCall:
    """Source method+URL from the generated operation, send the raw body.

    Used for the AQL/UQL/federated query operations. Their OpenAPI
    ``parameters`` field is typed as an array of *objects*, but the facade's
    public API accepts positional scalar bind values (e.g. ``[1, "x"]``), which
    the server decodes leniently. Round-tripping those scalars through the
    generated attrs model would reject them, so we bind the spec-governed
    method+URL from the generated endpoint while preserving the facade's body
    verbatim. ``model_cls`` is referenced only to keep the spec linkage explicit.
    """
    assert model_cls is not None
    call = _normalize(get_kwargs(body=_EMPTY_BODY_SENTINEL))
    return RestCall(method=call.method, endpoint=call.endpoint, json=body)


class _EmptyBody:
    """Minimal stand-in so the generated _get_kwargs can build method+URL.

    ``_get_kwargs`` calls ``body.to_dict()``; we only need the method/url it
    returns, so a no-op ``to_dict`` is sufficient and the result is discarded.
    """

    @staticmethod
    def to_dict() -> dict[str, Any]:
        return {}


_EMPTY_BODY_SENTINEL = _EmptyBody()


