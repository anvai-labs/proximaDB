# Generate the typed Python REST transport (src/proximadb_sdk/_generated/rest)
# from the published OpenAPI spec (TD-126 Phase 4). Invoked by
# `make gen-python-sdk`.
#
# Pipeline:
#   1. Build/refresh an isolated venv pinned by codegen/requirements.txt
#      (see that file for the openapi-python-client version). It is kept separate from the SDK's runtime
#      deps because the generator's Typer CLI breaks on the SDK's newer click and
#      its internal models break on the SDK's newer pydantic.
#   2. Run openapi-python-client (3.1-native) directly on the published spec — no
#      3.1->3.0 down-conversion (unlike the Go / Rust progenitor pipelines).
#   3. Sync the generated package into src/proximadb_sdk/_generated/rest, prepend
#      a "do not edit" header to every generated module, and format with the
#      SDK's own black + isort so the artifact matches both a fresh regeneration
#      AND the Python Lint gate.
#
# Regenerating must be deterministic: the CI drift gate runs this and then
# `git diff --exit-code`s src/proximadb_sdk/_generated/rest.
set -euo pipefail

# Resolve paths relative to this script so it works from any cwd.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_ROOT="$(cd "${PY_DIR}/../.." && pwd)"

SPEC="${REPO_ROOT}/docs/openapi/proximadb-openapi.yaml"
OUT_DIR="${PY_DIR}/src/proximadb_sdk/_generated/rest"
CONFIG="${SCRIPT_DIR}/config.yaml"
REQS="${SCRIPT_DIR}/requirements.txt"

# Isolated generator venv (pinned). Lives under codegen/ and is git-ignored.
GEN_VENV="${GEN_VENV:-${SCRIPT_DIR}/.venv}"
BASE_PYTHON="${PYTHON:-python3}"

if [[ ! -x "${GEN_VENV}/bin/openapi-python-client" ]]; then
  echo "==> creating generator venv (${GEN_VENV})"
  "${BASE_PYTHON}" -m venv "${GEN_VENV}"
  "${GEN_VENV}/bin/pip" install --quiet --upgrade pip
  "${GEN_VENV}/bin/pip" install --quiet -r "${REQS}"
fi

TMP_OUT="$(mktemp -d -t proximadb-py-rest.XXXXXX)"
trap 'rm -rf "${TMP_OUT}"' EXIT

echo "==> generating Python REST transport from ${SPEC}"
"${GEN_VENV}/bin/openapi-python-client" generate \
  --path "${SPEC}" \
  --meta none \
  --output-path "${TMP_OUT}/rest" \
  --config "${CONFIG}" \
  --overwrite

echo "==> syncing into ${OUT_DIR}"
rm -rf "${OUT_DIR}"
mkdir -p "$(dirname "${OUT_DIR}")"
cp -R "${TMP_OUT}/rest" "${OUT_DIR}"

# Prepend a "do not edit" banner to every generated module. The hook
# scripts/check_no_agent_attribution.py explicitly permits a codegen file's own
# header, and the contract/drift gates depend on this dir being treated as
# generated.
echo "==> stamping do-not-edit headers"
BANNER_TMP="$(mktemp)"
cat > "${BANNER_TMP}" <<'EOF'
# @generated by openapi-python-client (TD-126 Phase 4) — DO NOT EDIT.
#
# Regenerate with `make gen-python-sdk`. Source of truth:
# docs/openapi/proximadb-openapi.yaml. The CI gate `python-sdk-codegen-drift`
# fails if this directory drifts from a fresh regeneration.
EOF
while IFS= read -r -d '' f; do
  cat "${BANNER_TMP}" "${f}" > "${f}.stamped"
  mv "${f}.stamped" "${f}"
done < <(find "${OUT_DIR}" -name '*.py' -print0)
rm -f "${BANNER_TMP}"

echo "==> formatting with the SDK's black + isort (deterministic pass)"
( cd "${PY_DIR}" && python -m isort "${OUT_DIR}" >/dev/null && python -m black --quiet "${OUT_DIR}" )

echo "==> done: ${OUT_DIR}"
