// Emit dist/index.mjs: the ESM entry package.json `exports["."].import` and
// `module` name.
//
// It is a thin ESM wrapper over the CommonJS build (dist/index.js), the
// Node-documented way to ship one implementation to both module systems: an
// `import` and a `require` get the SAME module instance (no dual-package
// hazard), and nothing depends on Node resolving extensionless relative
// imports -- which is why the previous separate `tsc -p tsconfig.esm.json`
// build (moduleResolution "bundler", output dist/esm/) could not be loaded by
// Node at all, and why v0.4.1 shipped an `import` target that did not exist.
//
// The named exports are read from the built CommonJS module rather than listed
// by hand, so a new export cannot be missing from the ESM entry.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(here, "..", "dist");
const require = createRequire(import.meta.url);
const cjs = require(path.join(dist, "index.js"));

const names = Object.keys(cjs).filter((n) => n !== "default" && n !== "__esModule").sort();
if (names.length === 0) {
  console.error("write-esm-entry: dist/index.js exports nothing -- refusing to write an empty ESM entry");
  process.exit(1);
}
for (const n of names) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n)) {
    console.error(`write-esm-entry: export name '${n}' is not a valid identifier`);
    process.exit(1);
  }
}
const body = [
  "// GENERATED by scripts/write-esm-entry.mjs -- ESM wrapper over the CommonJS build.",
  'import cjs from "./index.js";',
  `export const { ${names.join(", ")} } = cjs;`,
  "export default cjs.default;",
  "",
].join("\n");
writeFileSync(path.join(dist, "index.mjs"), body);
console.log(`write-esm-entry: dist/index.mjs re-exports ${names.length} names + default`);
