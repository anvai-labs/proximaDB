/// gRPC handler bundling the per-process `RankServices` singleton.
///
/// Constructed once at server startup (same `Arc<RankServices>` the REST
/// path holds) and bound to the tonic server. The actual tonic
/// `RankServiceServer` wrapper will be generated by the next proto
/// regeneration pass; until then this struct is exercised directly by
/// integration tests and reachable from any future hand-written tonic
/// service shim.
#[derive(Clone)]
pub struct RankServiceImpl {
    services: Arc<RankServices>,
}

impl RankServiceImpl {
    /// Build a handler around the shared `RankServices`.
    pub fn new(services: Arc<RankServices>) -> Self {
        Self { services }
    }

    /// gRPC entry point. Signature matches what tonic-build emits for
    /// `service RankService { rpc RankSearch(...) returns (...); }`.
    ///
    /// Drives:
    /// 1. Decode prost request → REST DTO (lossless — they're mirrors).
    /// 2. Resolve per-profile second-phase scorer up-front (same as the REST
    ///    path; cheap DashMap lookup before the inner future starts).
    /// 3. Call `handle_rank_search` — same code path the REST handler
    ///    drives, so behaviour stays in lockstep.
    /// 4. Encode REST DTO → prost response (lossless), wrap in
    ///    `tonic::Response`.
    /// 5. Map `RankError` → `tonic::Status` (mirrors REST's `ApiError`
    ///    mapping).
    pub async fn rank_search(
        &self,
        request: tonic::Request<proto_ranking::RankSearchRequest>,
    ) -> Result<tonic::Response<proto_ranking::RankSearchResponse>, tonic::Status> {
        // The collection is resolved within the request tenant.
        let request_tenant = crate::network::grpc::auth::resolved_tenant_id(&request)?;
        let proto_req = request.into_inner();
        let mut rest_req = proto_to_rest_request(proto_req);
        rest_req.request_tenant = Some(request_tenant);
        let second_phase_scorer = rest_req
            .rank_profile
            .as_deref()
            .and_then(|name| self.services.second_phase_scorer(name));
        let rest_resp = handle_rank_search_with_metrics(
            rest_req,
            self.services.profile_registry.as_ref(),
            self.services.candidate_provider.as_ref(),
            self.services.blueprint_factory.clone(),
            second_phase_scorer,
            self.services.rerank_config.clone(),
            // R-7c.4d follow-up: forward the metrics handle so the
            // gRPC path emits NFR-8 observations alongside REST.
            // None when RankServices was constructed without
            // `.with_metrics(...)` — keeps the noop fast path.
            self.services.metrics.clone(),
        )
        .await
        .map_err(rank_error_to_status)?;
        Ok(tonic::Response::new(rest_to_proto_response(rest_resp)))
    }
}

// =========================================================================
// Translation: prost → REST DTO (request direction)
// =========================================================================

fn proto_to_rest_request(p: proto_ranking::RankSearchRequest) -> RankSearchRequest {
    RankSearchRequest {
        collection: p.collection,
        query_vector: p.query_vector,
        query_text: p.query_text,
        k: p.k as usize,
        rank_profile: p.rank_profile,
        rank_overrides: p.rank_overrides.map(proto_to_rest_overrides),
        request_tenant: None,
    }
}

fn proto_to_rest_overrides(p: proto_ranking::RankOverrides) -> RankOverrides {
    RankOverrides {
        second_phase: p.second_phase.map(proto_to_rest_phase_override),
        global_phase: p.global_phase.map(proto_to_rest_phase_override),
    }
}

fn proto_to_rest_phase_override(p: proto_ranking::PhaseOverride) -> PhaseOverride {
    PhaseOverride {
        rerank_count: p.rerank_count,
        batch_size: p.batch_size,
    }
}

// =========================================================================
// Translation: REST DTO → prost (response direction)
// =========================================================================

fn rest_to_proto_response(r: RankSearchResponse) -> proto_ranking::RankSearchResponse {
    proto_ranking::RankSearchResponse {
        hits: r.hits.into_iter().map(rest_to_proto_hit).collect(),
        phase_truncated: r.phase_truncated,
        rank_profile: r.rank_profile,
        rank_profile_version: r.rank_profile_version,
    }
}

fn rest_to_proto_hit(h: ScoredHitDto) -> proto_ranking::ScoredHit {
    proto_ranking::ScoredHit {
        id: h.id,
        score: h.score,
        score_vector: h.score_vector.map(rest_to_proto_score_vector),
        match_features: h.match_features,
        summary_features: h.summary_features,
    }
}

fn rest_to_proto_score_vector(sv: ScoreVectorDto) -> proto_ranking::ScoreVector {
    proto_ranking::ScoreVector {
        primary: sv.primary,
        phase: sv.phase as u32,
        components: sv
            .components
            .into_iter()
            .map(kernel_to_proto_component)
            .collect(),
    }
}

fn kernel_to_proto_component(c: KernelScoreComponent) -> proto_ranking::ScoreComponent {
    proto_ranking::ScoreComponent {
        name: c.name,
        value: c.value,
        weight: c.weight,
        contribution: c.contribution,
    }
}

// =========================================================================
// Error mapping — keep in lockstep with rest::canonical::rank::rank_search_dispatch
// =========================================================================

fn rank_error_to_status(e: RankError) -> tonic::Status {
    match e {
        RankError::ProfileNotFound(name) => {
            tonic::Status::not_found(format!("rank profile not found: {name}"))
        }
        RankError::InvalidProfile(msg) => tonic::Status::invalid_argument(msg),
        RankError::InvalidArgument(msg) => tonic::Status::invalid_argument(msg),
        RankError::CollectionNotFound(collection) => {
            tonic::Status::not_found(format!("Collection not found: {collection}"))
        }
        other => tonic::Status::internal(format!("rank pipeline failed: {other}")),
    }
}

// Suppress dead-code warnings for translation helpers and ScoreVector /
// PhaseId imports — they're load-bearing for the public API shape but the
// compiler can't see that from this module alone yet (tonic-generated
// callers land in a follow-up regen pass).
#[allow(dead_code)]
fn _shape_lock(sv: &ScoreVector) -> PhaseId {
    sv.phase
}

