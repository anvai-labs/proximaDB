//! gRPC handler for the multi-phase ranking pipeline (R-7c.4a.1).
//!
//! This is the gRPC twin of the REST handler in
//! [`crate::network::rest::canonical::rank::rank_search_dispatch`]. Both share the
//! same in-process `handle_rank_search` core — only the wire format and
//! the error envelope differ. Keeping the bridge thin and centralised
//! means future profile / phase changes flow to both protocols without
//! divergence.
//!
//! Wire shape: `proximadb_proto::ranking::{RankSearchRequest,
//! RankSearchResponse, ...}` — the hand-written prost mirrors of
//! `proto/proximadb/v1/ranking.proto`. When the proto regen pass folds
//! `ranking.proto` into the generated set, the generated
//! `RankServiceServer<T: RankService>` trait method body is a single
//! line: `self.rank_search_inner(request).await` — the signature here
//! is intentionally identical to what tonic-build emits.
//!
//! Error mapping (mirrors the REST `rank_search_dispatch` policy):
//! - `RankError::ProfileNotFound` → `tonic::Status::not_found`
//! - `RankError::InvalidProfile` → `tonic::Status::invalid_argument`
//! - everything else              → `tonic::Status::internal`
//!
//! Spec: roadmap/RANKING_FRAMEWORK_SPEC_2026_05_23.md §4.9.2.

